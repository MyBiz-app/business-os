// Works out which message namespaces the browser can read on each part of the site, so a page
// ships only the words its own screens use (one language, and only the namespaces it needs).
//
// A "scope" is a part of the app with its own layout: the root (shared shell, error pages and
// the small public routes), the marketing site, the sign-in screens, the business web app, the
// business screens under it, and the MyBiz console. A scope's list is every namespace named by a
// client component (or any file calling `useTranslations`) that the scope's files import,
// directly or through other files: `useTranslations("auth")`, `t("account.title")`.
//
// Run `pnpm --filter web i18n:client` after adding a client screen or a new message namespace;
// `src/lib/client-namespaces.test.ts` fails when the committed list is out of date.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "src");
const OUT = join(SRC, "i18n", "client-namespaces.ts");
const MESSAGES = join(root, "..", "..", "packages", "i18n", "messages", "he.json");

/** Directory (under src/app) -> scope. Longest prefix wins; everything else is "root". */
const SCOPE_DIRS = [
  ["app/(marketing)", "marketing"],
  ["app/(auth)", "auth"],
  ["app/(app)/(tenant)", "tenant"],
  ["app/(app)/platform", "platform"],
  ["app/(app)", "app"],
];

function* walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(path);
    else if (/\.(ts|tsx)$/.test(entry.name) && !/\.test\.tsx?$/.test(entry.name)) yield path;
  }
}

const rel = (file) => file.slice(SRC.length + 1).split("\\").join("/");

function scopeOf(file) {
  const path = rel(file);
  for (const [dir, scope] of SCOPE_DIRS) if (path.startsWith(`${dir}/`)) return scope;
  return "root";
}

function resolveImport(from, spec) {
  let base;
  if (spec.startsWith("@/")) base = join(SRC, spec.slice(2));
  else if (spec.startsWith(".")) base = resolve(dirname(from), spec);
  else return undefined;
  for (const candidate of [base, `${base}.ts`, `${base}.tsx`, join(base, "index.ts"), join(base, "index.tsx")]) {
    if (/\.tsx?$/.test(candidate) && existsSync(candidate)) return candidate;
  }
  return undefined;
}

export function scanClientNamespaces() {
  const namespaces = Object.keys(JSON.parse(readFileSync(MESSAGES, "utf8")));
  const files = [...walk(SRC)].filter((file) => file !== OUT);
  const own = new Map(); // file -> namespaces named in it (client-side files only)
  const imports = new Map(); // file -> files it imports
  for (const file of files) {
    const source = readFileSync(file, "utf8");
    const client = /^\s*["']use client["']/m.test(source) || source.includes("useTranslations(");
    const used = new Set();
    if (client) {
      for (const ns of namespaces) {
        if (new RegExp(`(?:useTranslations\\(\\s*["']${ns}\\b|["'\`]${ns}\\.)`).test(source)) used.add(ns);
      }
    }
    own.set(file, used);
    const targets = new Set();
    for (const match of source.matchAll(/(?:from\s*|import\s*\(\s*|import\s+)["']([^"']+)["']/g)) {
      const target = resolveImport(file, match[1]);
      if (target) targets.add(target);
    }
    imports.set(file, targets);
  }
  const result = {};
  for (const [, scope] of [...SCOPE_DIRS, ["", "root"]]) result[scope] = new Set();
  for (const file of files) {
    const scope = scopeOf(file);
    const seen = new Set();
    const stack = [file];
    while (stack.length) {
      const current = stack.pop();
      if (seen.has(current)) continue;
      seen.add(current);
      for (const ns of own.get(current) ?? []) result[scope].add(ns);
      for (const next of imports.get(current) ?? []) stack.push(next);
    }
  }
  return Object.fromEntries(Object.entries(result).map(([scope, set]) => [scope, [...set].sort()]));
}

export function render(lists) {
  return `// Generated by scripts/client-namespaces.mjs: do not edit by hand.
/** Message namespaces the browser can read, by part of the site. A page gets "root" plus the
 * scopes of its layouts (see ScopedMessages). Everything else stays on the server. */
export const CLIENT_NAMESPACES: Record<"root" | "marketing" | "auth" | "app" | "tenant" | "platform", readonly string[]> = ${JSON.stringify(lists, null, 2)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const lists = scanClientNamespaces();
  writeFileSync(OUT, render(lists));
  console.log(Object.entries(lists).map(([scope, list]) => `${scope}: ${list.length}`).join(", "));
}
